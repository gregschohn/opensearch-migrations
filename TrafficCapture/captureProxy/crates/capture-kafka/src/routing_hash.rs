//! Java-compatible connection-to-partition routing hash.
//!
//! The capture protocol routes a new connection to a partition with
//!
//! ```text
//! sortedAscendingUnique(assignedPartitions)[toPositive(murmur2(utf8(connectionId))) % len]
//! ```
//!
//! which is exactly what `CaptureRoutingState` does in Java: `positiveHash` is
//! `Utils.toPositive(Utils.murmur2(value.getBytes(StandardCharsets.UTF_8)))`, and the partition
//! list comes from a `TreeSet<Integer>` (unique, ascending).
//!
//! This must match the Java Kafka client bit-for-bit, because an existing connection's partition is
//! immutable and a Rust proxy may share a topic with records written under the Java scheme. Rust's
//! own hashers are **not** interchangeable here.
//!
//! Verified against golden vectors generated by `org.apache.kafka.common.utils.Utils` from
//! kafka-clients 4.2.0 (see `capture-test-support/fixtures/murmur2-golden.json`, regenerated by
//! `qualification/java-fixtures/GenVectors.java`): 68 connection ids x 8 partition sets = 544
//! routing decisions, zero mismatches.

/// Kafka's `Utils.murmur2`. Returns the same signed 32-bit value as the Java implementation.
///
/// This is Kafka's own Murmur2 variant, not canonical `MurmurHash2`: note the seed, the `+`
/// (not `|`) block assembly, and the switch fall-through that applies a single trailing multiply
/// for any nonzero tail length.
///
/// # Panics
///
/// Panics if `data` is longer than [`i32::MAX`]. Java's `byte[] data` cannot exceed that length, so
/// there is no Java behavior to match beyond it, and silently truncating the length would produce a
/// hash that disagrees with Java.
#[must_use]
pub fn murmur2(data: &[u8]) -> i32 {
    const M: i32 = 0x5bd1_e995_u32.cast_signed();
    const R: u32 = 24;
    const SEED: i32 = 0x9747_b28c_u32.cast_signed();

    let length = i32::try_from(data.len())
        .expect("murmur2 input must fit in a Java byte[] (i32::MAX bytes)");
    let mut h: i32 = SEED ^ length;

    for chunk in data.chunks_exact(4) {
        let mut k: i32 = i32::from(chunk[0])
            .wrapping_add(i32::from(chunk[1]) << 8)
            .wrapping_add(i32::from(chunk[2]) << 16)
            .wrapping_add(i32::from(chunk[3]) << 24);
        k = k.wrapping_mul(M);
        k ^= ushr(k, R);
        k = k.wrapping_mul(M);
        h = h.wrapping_mul(M);
        h ^= k;
    }

    // Java's `switch (length % 4)` falls through from 3 -> 2 -> 1, so the trailing bytes are all
    // mixed in and `h *= m` runs exactly once for any nonzero remainder.
    let tail = data.chunks_exact(4).remainder();
    if !tail.is_empty() {
        if tail.len() == 3 {
            h ^= i32::from(tail[2]) << 16;
        }
        if tail.len() >= 2 {
            h ^= i32::from(tail[1]) << 8;
        }
        h ^= i32::from(tail[0]);
        h = h.wrapping_mul(M);
    }

    h ^= ushr(h, 13);
    h = h.wrapping_mul(M);
    h ^= ushr(h, 15);
    h
}

/// Kafka's `Utils.toPositive`: clears the sign bit rather than taking an absolute value, so
/// `i32::MIN` maps to `0` instead of overflowing.
#[must_use]
pub fn to_positive(value: i32) -> i32 {
    value & 0x7fff_ffff
}

/// Java's `>>>` (logical shift right) on a 32-bit signed integer.
fn ushr(value: i32, bits: u32) -> i32 {
    value.cast_unsigned().wrapping_shr(bits).cast_signed()
}

/// Selects the partition for `connection_id` from `sorted_partitions`.
///
/// # Panics
///
/// Panics if `sorted_partitions` is empty. A routing generation with no partitions is internal
/// state corruption, which the capture protocol requires to terminate the process rather than be
/// silently tolerated; callers must reject an empty assignment before reaching this point.
///
/// `sorted_partitions` must already be unique and ascending, matching the Java `TreeSet` ordering.
/// Passing an unsorted list silently selects a different partition than Java would.
#[must_use]
pub fn select_partition(connection_id: &str, sorted_partitions: &[i32]) -> i32 {
    assert!(
        !sorted_partitions.is_empty(),
        "routing generation has no partitions; this is capture state corruption"
    );
    debug_assert!(
        sorted_partitions.windows(2).all(|w| w[0] < w[1]),
        "partitions must be unique and ascending to match Java TreeSet ordering"
    );
    // `to_positive` clears the sign bit, so this is always a valid index magnitude.
    let positive = to_positive(murmur2(connection_id.as_bytes()));
    let index = usize::try_from(positive).expect("to_positive never returns a negative value")
        % sorted_partitions.len();
    sorted_partitions[index]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn to_positive_clears_sign_bit_without_overflow() {
        assert_eq!(to_positive(0), 0);
        assert_eq!(to_positive(-1), i32::MAX);
        // `abs()` would panic/overflow here; Java's masking yields 0.
        assert_eq!(to_positive(i32::MIN), 0);
    }

    #[test]
    fn empty_input_matches_java_seed_mixing() {
        // Measured from kafka-clients 4.2.0: Utils.murmur2(new byte[0]) == 275646681.
        // The exhaustive cross-language comparison lives in tests/routing_hash_golden.rs.
        assert_eq!(murmur2(b""), 275_646_681);
    }

    #[test]
    fn single_partition_assignment_always_selects_it() {
        for id in ["", "a", "0f3c9a1b00000001", "😀"] {
            assert_eq!(select_partition(id, &[7]), 7);
        }
    }

    #[test]
    fn selection_is_stable_for_the_same_input() {
        let parts = [0, 1, 2, 3, 4, 5, 6, 7];
        let first = select_partition("0f3c9a1b00000001", &parts);
        for _ in 0..16 {
            assert_eq!(select_partition("0f3c9a1b00000001", &parts), first);
        }
    }
}
