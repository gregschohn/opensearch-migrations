fn check_cloudwatch(dashboard: &Value, findings: &mut Findings) {
    match dashboard {
        Value::Array(items)
            if items.first().and_then(Value::as_str) == Some(CLOUDWATCH_NAMESPACE)
                && items.get(1).is_some_and(Value::is_string) =>
        {
            check_cloudwatch_metric_array(items, findings);
        }
        Value::Array(items) => items
            .iter()
            .for_each(|item| check_cloudwatch(item, findings)),
        Value::Object(map) => {
            for (key, child) in map {
                match (key.as_str(), child) {
                    ("expression", Value::String(expression)) => {
                        check_cloudwatch_expression(expression, findings);
                    }
                    _ => check_cloudwatch(child, findings),
                }
            }
        }
        _ => {}
    }
}

/// `["OpenSearchMigrations", <name>, <dimension>, <value>, ..., {<options>}]`.
///
/// A metric array names one metric with **exactly** the listed dimensions, so the dimensions
/// beyond [`COLLECTOR_DIMENSIONS`] must be exactly the instrument's.
fn check_cloudwatch_metric_array(items: &[Value], findings: &mut Findings) {
    let name = items[1].as_str().unwrap_or_default();
    let strings: Vec<&str> = items[2..].iter().map_while(Value::as_str).collect();
    let dimensions: BTreeMap<&str, &str> = strings
        .chunks(2)
        .filter_map(|pair| match pair {
            [key, value] => Some((*key, *value)),
            _ => None,
        })
        .collect();
    let library = dimensions.get("OTelLib").copied();
    if library.is_some_and(|library| library != SCOPE_NAME) {
        return;
    }
    if library.is_none() {
        if contract::instrument(name).is_some() || looks_like_a_proxy_name(name) {
            findings.problems.push(format!(
                "metric array {strings:?} for `{name}` does not pin OTelLib=\"{SCOPE_NAME}\""
            ));
        }
        return;
    }
    if !strings.len().is_multiple_of(2) || strings.iter().any(|item| matches!(*item, "." | "...")) {
        findings.problems.push(format!(
            "metric array for `{name}` uses a form this test cannot read: {strings:?}"
        ));
        return;
    }
    let Some(row) = contract::instrument(name) else {
        findings.problems.push(format!(
            "CloudWatch metric `{name}` (OTelLib=\"{SCOPE_NAME}\") is not a proxy instrument"
        ));
        return;
    };
    let queried: BTreeSet<&str> = dimensions
        .keys()
        .copied()
        .filter(|key| !COLLECTOR_DIMENSIONS.contains(key))
        .collect();
    if queried != dimension_keys(row) {
        findings.problems.push(format!(
            "CloudWatch metric array for `{name}` names dimensions {queried:?}; the proxy emits {:?}",
            dimension_keys(row)
        ));
    }
    for (key, value) in &dimensions {
        check_dimension_value(row, key, value, &mut findings.problems);
    }
    findings.reference(row, name);
}

/// Every `SEARCH('...'` query in a metric-math expression.
fn check_cloudwatch_expression(expression: &str, findings: &mut Findings) {
    let pinned = format!("OTelLib=\"{SCOPE_NAME}\"");
    let mut proxy_searches = 0;
    let mut rest = expression;
    while let Some(start) = rest.find("SEARCH('") {
        let query_start = start + "SEARCH('".len();
        let Some(length) = rest[query_start..].find('\'') else {
            findings
                .problems
                .push(format!("unterminated SEARCH in `{expression}`"));
            return;
        };
        let query = &rest[query_start..query_start + length];
        if check_cloudwatch_search(query, findings) {
            proxy_searches += 1;
        }
        rest = &rest[query_start + length..];
    }
    // Every mention of the proxy's scope must have been inside a SEARCH this test read.
    if expression.matches(pinned.as_str()).count() != proxy_searches {
        findings.problems.push(format!(
            "`{expression}` mentions {pinned} outside a SEARCH this test can read"
        ));
    }
}

/// Checks one `SEARCH` query; returns whether it is a proxy query.
///
/// `{Namespace,dim,...} MetricName="x" OTelLib="captureProxy" key="value"`. A schema in braces
/// matches only metrics with exactly that dimension set; without one, the filters must at least be
/// dimensions the instrument has.
fn check_cloudwatch_search(query: &str, findings: &mut Findings) -> bool {
    let (schema, filter_text) = match query
        .strip_prefix('{')
        .and_then(|body| body.split_once('}'))
    {
        Some((schema, rest)) => (
            Some(schema.split(',').map(str::trim).collect::<Vec<_>>()),
            rest,
        ),
        None => (None, query),
    };
    let filters = quoted_filters(filter_text);
    let name = filters.get("MetricName").copied().unwrap_or_default();
    match filters.get("OTelLib").copied() {
        Some(SCOPE_NAME) => {}
        Some(_) => return false,
        None => {
            if contract::instrument(name).is_some() || looks_like_a_proxy_name(name) {
                findings.problems.push(format!(
                    "SEARCH for `{name}` does not pin OTelLib=\"{SCOPE_NAME}\": {query}"
                ));
            }
            return false;
        }
    }
    let Some(row) = contract::instrument(name) else {
        findings.problems.push(format!(
            "SEARCH names `{name}` with OTelLib=\"{SCOPE_NAME}\" but it is not a proxy instrument: {query}"
        ));
        return true;
    };
    let expected = dimension_keys(row);
    match schema.as_deref() {
        Some([namespace, dimensions @ ..]) => {
            let queried: BTreeSet<&str> = dimensions
                .iter()
                .copied()
                .filter(|key| !COLLECTOR_DIMENSIONS.contains(key))
                .collect();
            if *namespace != CLOUDWATCH_NAMESPACE || queried != expected {
                findings.problems.push(format!(
                    "SEARCH schema for `{name}` is {{{namespace},{}}}; the proxy emits {expected:?} in {CLOUDWATCH_NAMESPACE}",
                    dimensions.join(",")
                ));
            }
        }
        _ => {
            for key in filters.keys() {
                if !matches!(*key, "MetricName" | "Namespace")
                    && !COLLECTOR_DIMENSIONS.contains(key)
                    && !expected.contains(key)
                {
                    findings.problems.push(format!(
                        "SEARCH for `{name}` filters on `{key}`, which is not one of its dimensions {expected:?}"
                    ));
                }
            }
        }
    }
    for (key, value) in &filters {
        check_dimension_value(row, key, value, &mut findings.problems);
    }
    findings.reference(row, name);
    true
}

/// `key="value"` pairs, keyed by `key`.
fn quoted_filters(text: &str) -> BTreeMap<&str, &str> {
    let mut filters = BTreeMap::new();
    let mut rest = text;
    while let Some(equals) = rest.find("=\"") {
        let key_start = rest[..equals]
            .rfind(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .map_or(0, |position| position + 1);
        let value_start = equals + 2;
        let Some(length) = rest[value_start..].find('"') else {
            break;
        };
        filters.insert(
            &rest[key_start..equals],
            &rest[value_start..value_start + length],
        );
        rest = &rest[value_start + length + 1..];
    }
    filters
}

