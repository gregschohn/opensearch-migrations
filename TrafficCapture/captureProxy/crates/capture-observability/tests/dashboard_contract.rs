/// One vector selector: `name{label op "value", ...}`.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Selector {
    metric: String,
    matchers: Vec<(String, String, String)>,
}

impl Selector {
    fn equality(&self, label: &str) -> Option<&str> {
        self.matchers
            .iter()
            .find(|(key, op, _)| key == label && op == "=")
            .map(|(_, _, value)| value.as_str())
    }

    /// The metric name, or its `__name__` equality matcher.
    fn name(&self) -> &str {
        if self.metric.is_empty() {
            self.equality("__name__").unwrap_or_default()
        } else {
            &self.metric
        }
    }
}

/// The selectors and grouping labels of one `PromQL` expression.
#[derive(Debug, Default, PartialEq, Eq)]
struct PromQuery {
    selectors: Vec<Selector>,
    grouping: BTreeSet<String>,
}

/// Aggregation operators and binary keywords: identifiers that are never a metric name.
const PROMQL_KEYWORDS: &[&str] = &[
    "sum",
    "min",
    "max",
    "avg",
    "group",
    "stddev",
    "stdvar",
    "count",
    "count_values",
    "bottomk",
    "topk",
    "quantile",
    "limitk",
    "limit_ratio",
    "and",
    "or",
    "unless",
    "bool",
    "offset",
    "atan2",
];

/// Keywords followed by a parenthesised label list.
const PROMQL_LABEL_LISTS: &[&str] = &[
    "by",
    "without",
    "on",
    "ignoring",
    "group_left",
    "group_right",
];

/// A small `PromQL` lexer: enough to find every vector selector and every grouping label.
///
/// String literals, range and subquery brackets, numbers and durations, and Grafana variables
/// (`$__rate_interval`, `${name:raw}`) are skipped. An identifier followed by `(` is a function, a
/// keyword is an operator, and any other identifier is a metric name, with its matchers when `{`
/// follows.
fn parse_promql(expression: &str) -> PromQuery {
    let bytes = expression.as_bytes();
    let mut query = PromQuery::default();
    let mut at = 0;
    while at < bytes.len() {
        match bytes[at] {
            quote @ (b'"' | b'\'' | b'`') => at = string_end(bytes, at, quote),
            b'[' => at = closing(bytes, at, b']') + 1,
            b'$' if bytes.get(at + 1) == Some(&b'{') => at = closing(bytes, at, b'}') + 1,
            b'$' | b'0'..=b'9' => {
                at += 1;
                while at < bytes.len()
                    && (bytes[at].is_ascii_alphanumeric() || b"._".contains(&bytes[at]))
                {
                    at += 1;
                }
            }
            b'{' => {
                let end = closing(bytes, at, b'}');
                query.selectors.push(Selector {
                    metric: String::new(),
                    matchers: parse_matchers(&expression[at + 1..end]),
                });
                at = end + 1;
            }
            byte if byte.is_ascii_alphabetic() || byte == b'_' || byte == b':' => {
                let start = at;
                while at < bytes.len()
                    && (bytes[at].is_ascii_alphanumeric() || b"_:".contains(&bytes[at]))
                {
                    at += 1;
                }
                let identifier = &expression[start..at];
                let next = (at..bytes.len())
                    .find(|&position| bytes[position] != b' ')
                    .unwrap_or(bytes.len());
                let followed_by = bytes.get(next).copied();
                if PROMQL_LABEL_LISTS.contains(&identifier) && followed_by == Some(b'(') {
                    let end = closing(bytes, next, b')');
                    query.grouping.extend(
                        expression[next + 1..end]
                            .split(',')
                            .map(str::trim)
                            .filter(|label| !label.is_empty())
                            .map(str::to_owned),
                    );
                    at = end + 1;
                } else if PROMQL_KEYWORDS.contains(&identifier) || followed_by == Some(b'(') {
                    // An aggregation, a function call, or a binary operator keyword.
                } else if followed_by == Some(b'{') {
                    let end = closing(bytes, next, b'}');
                    query.selectors.push(Selector {
                        metric: identifier.to_owned(),
                        matchers: parse_matchers(&expression[next + 1..end]),
                    });
                    at = end + 1;
                } else {
                    query.selectors.push(Selector {
                        metric: identifier.to_owned(),
                        matchers: Vec::new(),
                    });
                }
            }
            _ => at += 1,
        }
    }
    query
}

/// The index just past the string literal opened at `start`.
fn string_end(bytes: &[u8], start: usize, quote: u8) -> usize {
    let mut at = start + 1;
    while at < bytes.len() && bytes[at] != quote {
        at += if bytes[at] == b'\\' { 2 } else { 1 };
    }
    at + 1
}

/// The index of the `close` byte that ends the group opened at `open`, skipping string literals.
fn closing(bytes: &[u8], open: usize, close: u8) -> usize {
    let mut at = open + 1;
    while at < bytes.len() {
        match bytes[at] {
            quote @ (b'"' | b'\'' | b'`') => at = string_end(bytes, at, quote),
            byte if byte == close => return at,
            _ => at += 1,
        }
    }
    panic!(
        "unbalanced `{}` in `{}`",
        char::from(close),
        String::from_utf8_lossy(bytes)
    );
}

/// `label op "value"` matchers, separated by commas.
fn parse_matchers(text: &str) -> Vec<(String, String, String)> {
    let mut matchers = Vec::new();
    let mut rest = text.trim_start_matches([' ', ',']);
    while !rest.is_empty() {
        let label_end = rest
            .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .unwrap_or(rest.len());
        let (label, after_label) = rest.split_at(label_end);
        let after_label = after_label.trim_start();
        let op = ["=~", "!~", "!=", "="]
            .into_iter()
            .find(|op| after_label.starts_with(op))
            .unwrap_or_else(|| panic!("cannot read matcher `{rest}` in `{{{text}}}`"));
        let after_op = after_label[op.len()..].trim_start();
        let quote = after_op.as_bytes().first().copied().unwrap_or(b'"');
        let end = string_end(after_op.as_bytes(), 0, quote);
        let value = &after_op[1..end - 1];
        matchers.push((label.to_owned(), op.to_owned(), value.to_owned()));
        rest = after_op[end..].trim_start_matches([' ', ',']);
    }
    matchers
}

/// Checks every proxy selector in one `PromQL` consumer.
fn check_promql(expressions: &[String], findings: &mut Findings) {
    for expression in expressions {
        let query = parse_promql(expression);
        let mut every_selector_is_proxy = !query.selectors.is_empty();
        let mut proxy_rows: Vec<(&'static Instrument, SeriesPart)> = Vec::new();
        for selector in &query.selectors {
            match check_promql_selector(selector, expression, findings) {
                Some(resolved) => proxy_rows.push(resolved),
                None => every_selector_is_proxy = false,
            }
        }
        // Grouping labels are attributable only when nothing but proxy series is aggregated.
        if every_selector_is_proxy {
            for label in &query.grouping {
                let identity = PROMETHEUS_IDENTITY_LABELS.contains(&label.as_str());
                let bucket = label == "le"
                    && proxy_rows
                        .iter()
                        .all(|(_, part)| *part == SeriesPart::Bucket);
                let dimension = proxy_rows.iter().all(|(row, _)| {
                    row.dimensions
                        .iter()
                        .any(|dimension| dimension.key == label)
                });
                if !(identity || bucket || dimension) {
                    findings.problems.push(format!(
                        "groups proxy series by `{label}`, which they do not carry: {expression}"
                    ));
                }
            }
        }
    }
}

/// Checks one selector; returns its contract row when it is a proxy series that resolves.
fn check_promql_selector(
    selector: &Selector,
    expression: &str,
    findings: &mut Findings,
) -> Option<(&'static Instrument, SeriesPart)> {
    let name = selector.name();
    let scope = selector.equality("otel_scope_name");
    let job = selector.equality("exported_job");
    let pinned_to_proxy = scope == Some(SCOPE_NAME) || job == Some(SERVICE_NAME);
    let pinned_elsewhere = scope.is_some_and(|scope| scope != SCOPE_NAME)
        || job.is_some_and(|job| job != SERVICE_NAME);
    let resolved = resolve_series(name);
    if pinned_elsewhere {
        // Legitimate for a name the replayer shares; for a proxy-only name it means the proxy's
        // scope or service.name no longer matches what the dashboard pins.
        if let Some((row, _)) = resolved
            && !shared_with_replayer(row)
        {
            findings.problems.push(format!(
                "`{name}` is a proxy-only series but is pinned to otel_scope_name={scope:?} / exported_job={job:?}; \
                 the proxy exports scope `{SCOPE_NAME}` and service.name `{SERVICE_NAME}`: {expression}"
            ));
        }
        return None;
    }
    if !(pinned_to_proxy || resolved.is_some() || looks_like_a_proxy_name(name)) {
        return None;
    }
    let Some((row, part)) = resolved else {
        let hint = instrument_prefixing(name).map_or_else(String::new, |row| {
            format!(
                " (the proxy exports `{}` as `{}`)",
                row.name,
                row.exported_series_name()
            )
        });
        findings.problems.push(format!(
            "`{name}` is not a series the proxy exports{hint}: {expression}"
        ));
        return None;
    };
    findings.reference(row, name);
    if shared_with_replayer(row) && !pinned_to_proxy {
        findings.unscoped_shared.insert(name.to_owned());
    }
    for (label, _, value) in &selector.matchers {
        if PROMETHEUS_IDENTITY_LABELS.contains(&label.as_str()) || label == "__name__" {
            continue;
        }
        if label == "le" {
            if part != SeriesPart::Bucket {
                findings
                    .problems
                    .push(format!("`le` on non-bucket series `{name}`: {expression}"));
            }
            continue;
        }
        if !dimension_keys(row).contains(label.as_str()) {
            findings.problems.push(format!(
                "`{name}` is filtered on `{label}`, which is not one of its dimensions {:?}: {expression}",
                dimension_keys(row)
            ));
        }
        check_dimension_value(row, label, value, &mut findings.problems);
    }
    Some((row, part))
}

