#[test]
fn promql_selectors_matchers_and_grouping_are_extracted() {
    let query = parse_promql(
        "histogram_quantile(0.95, sum by (le) (rate(gatheringRequestDuration_milliseconds_bucket\
         {exported_job=\"capture\",le=~\"$show_max\"}[$__rate_interval]))) or vector(0)",
    );
    assert_eq!(
        query.selectors,
        vec![Selector {
            metric: "gatheringRequestDuration_milliseconds_bucket".to_owned(),
            matchers: vec![
                (
                    "exported_job".to_owned(),
                    "=".to_owned(),
                    "capture".to_owned()
                ),
                ("le".to_owned(), "=~".to_owned(), "$show_max".to_owned()),
            ],
        }]
    );
    assert_eq!(query.grouping, BTreeSet::from(["le".to_owned()]));

    // String arguments, subqueries and Grafana variables are not selectors.
    let query = parse_promql(
        "label_replace(sum by (exported_instance) (activeConnection_count{exported_job=\"capture\"}), \
         \"pod\", \"$1\", \"exported_instance\", \"([^_]+)_.*\") and on (pod) (up == 1) \
         + 1 - deriv(x[10m:1m]) * ${catchup_floor_seconds:raw}",
    );
    let names: Vec<&str> = query.selectors.iter().map(Selector::name).collect();
    assert_eq!(names, ["activeConnection_count", "up", "x"]);
    assert_eq!(
        query.grouping,
        BTreeSet::from(["exported_instance".to_owned(), "pod".to_owned()])
    );
}

