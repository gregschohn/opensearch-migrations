#[test]
fn the_cloudwatch_check_rejects_what_would_be_an_empty_widget() {
    let array = |items: &[&str]| -> Value {
        Value::Array(vec![Value::Array(
            items.iter().map(|item| Value::from(*item)).collect(),
        )])
    };
    let search = |query: &str| -> Value {
        serde_json::json!([{ "expression": format!("SUM(SEARCH('{query}', 'Sum', 60))") }])
    };
    let ok = [
        "OpenSearchMigrations",
        "fullRequest",
        "OTelLib",
        "captureProxy",
        "qualifier",
        "Q",
    ];
    assert!(cloudwatch_problems(&array(&ok)).is_empty());
    // A dimension the proxy does not emit: CloudWatch matches the exact set, so this is empty.
    let mut extra = ok.to_vec();
    extra.extend(["reason", "normal"]);
    assert_eq!(cloudwatch_problems(&array(&extra)).len(), 1);
    // An instrument that does not exist.
    assert_eq!(
        cloudwatch_problems(&array(&[
            "OpenSearchMigrations",
            "fullRequests",
            "OTelLib",
            "captureProxy"
        ]))
        .len(),
        1
    );
    // A schema search with the wrong dimension set, and an out-of-domain filter value.
    assert_eq!(
        cloudwatch_problems(&search(
            "{OpenSearchMigrations,OTelLib,qualifier} MetricName=\"capturePublishingRecordsAccepted\" OTelLib=\"captureProxy\""
        ))
        .len(),
        1
    );
    assert_eq!(
        cloudwatch_problems(&search(
            "{OpenSearchMigrations,OTelLib,outcome,qualifier,recordKind} MetricName=\"capturePublishingCompletions\" \
             OTelLib=\"captureProxy\" outcome=\"succeeded\""
        ))
        .len(),
        1
    );
    // A proxy metric with no OTelLib pin.
    assert_eq!(
        cloudwatch_problems(&search(
            "Namespace=\"OpenSearchMigrations\" MetricName=\"captureWritersActive\""
        ))
        .len(),
        1
    );
    // Another component's metric is not the proxy's business.
    assert!(
        cloudwatch_problems(&search(
            "{OpenSearchMigrations,OTelLib,qualifier,reason} MetricName=\"replayFatalFailures\" OTelLib=\"replayer\""
        ))
        .is_empty()
    );
}

