#[test]
fn the_consumers_read_exactly_the_externally_consumed_instruments() {
    let mut read_by: BTreeMap<&'static str, BTreeSet<&str>> = BTreeMap::new();
    let consumers = [
        (CLOUDWATCH_DASHBOARD, cloudwatch_findings()),
        (GRAFANA_DASHBOARD_TEMPLATE, grafana_findings()),
        (K6_DASHBOARD, k6_findings()),
    ]
    .into_iter()
    .chain(
        OPERATOR_SCRIPTS
            .iter()
            .map(|script| (*script, script_findings(script))),
    );
    for (consumer, findings) in consumers {
        for name in findings.references.keys() {
            read_by.entry(*name).or_default().insert(consumer);
        }
    }
    let read: BTreeSet<&str> = read_by.keys().copied().collect();
    let declared: BTreeSet<&str> = contract::INSTRUMENTS
        .iter()
        .filter(|row| row.exposure == Exposure::ExternallyConsumed)
        .map(|row| row.name)
        .collect();
    let undeclared: Vec<_> = read.difference(&declared).collect();
    let unread: Vec<_> = declared.difference(&read).collect();
    assert!(
        undeclared.is_empty() && unread.is_empty(),
        "read by a consumer but not Exposure::ExternallyConsumed: {undeclared:?}\n\
         Exposure::ExternallyConsumed but read by no consumer: {unread:?}\n\
         readers: {read_by:#?}"
    );
}

