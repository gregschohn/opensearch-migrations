/// Which part of an exported series a query names.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum SeriesPart {
    /// A counter or up-down counter series.
    Whole,
    /// A histogram's `_bucket` series, which alone carries `le`.
    Bucket,
    /// A histogram's `_sum` or `_count` series.
    SumOrCount,
}

/// The contract row whose exported Prometheus series `series` names.
fn resolve_series(series: &str) -> Option<(&'static Instrument, SeriesPart)> {
    contract::INSTRUMENTS.iter().find_map(|row| {
        let exported = row.exported_series_name();
        if row.kind == InstrumentKind::Histogram {
            match series.strip_prefix(exported.as_str())? {
                "_bucket" => Some((row, SeriesPart::Bucket)),
                "_sum" | "_count" => Some((row, SeriesPart::SumOrCount)),
                _ => None,
            }
        } else {
            (series == exported).then_some((row, SeriesPart::Whole))
        }
    })
}

/// The contract row whose instrument name starts `token` as `<name>_...`, for a diagnostic.
fn instrument_prefixing(token: &str) -> Option<&'static Instrument> {
    contract::INSTRUMENTS.iter().find(|row| {
        token == row.name
            || token
                .strip_prefix(row.name)
                .is_some_and(|rest| rest.starts_with('_'))
    })
}

/// Whether `token` is shaped like a proxy metric even though it may not resolve.
fn looks_like_a_proxy_name(token: &str) -> bool {
    let capture_prefixed = token
        .strip_prefix("capture")
        .and_then(|rest| rest.chars().next())
        .is_some_and(|first| first.is_ascii_uppercase());
    (capture_prefixed && token != SCOPE_NAME) || instrument_prefixing(token).is_some()
}

fn shared_with_replayer(row: &Instrument) -> bool {
    ACTIVITIES_SHARED_WITH_REPLAYER.iter().any(|activity| {
        [
            contract::activity_count_name(activity),
            contract::activity_duration_name(activity),
            contract::activity_exception_name(activity),
        ]
        .iter()
        .any(|generated| generated == row.name)
    })
}

/// Whether an instrument name is distinctive enough to recognise in free text.
fn distinctive(row: &Instrument) -> bool {
    row.name.bytes().any(|byte| byte.is_ascii_uppercase())
}

fn dimension_keys(row: &Instrument) -> BTreeSet<&'static str> {
    row.dimensions
        .iter()
        .map(|dimension| dimension.key)
        .collect()
}

/// A problem if `value` is outside the closed domain of `row`'s dimension `key`.
fn check_dimension_value(row: &Instrument, key: &str, value: &str, problems: &mut Vec<String>) {
    let Some(dimension) = row.dimensions.iter().find(|dimension| dimension.key == key) else {
        return;
    };
    if let DimensionDomain::Closed(values) = dimension.domain
        && !value.contains('$')
        && !values.contains(&value)
    {
        problems.push(format!(
            "`{}` dimension `{key}` never takes the value `{value}`; it takes {values:?}",
            row.name
        ));
    }
}

/// What the consumers were found to read.
#[derive(Debug, Default)]
struct Findings {
    /// Contract instrument name to the strings consumers wrote for it.
    references: BTreeMap<&'static str, BTreeSet<String>>,
    /// One line per violation.
    problems: Vec<String>,
    /// Grafana-style series of names shared with the replayer, queried without a proxy pin.
    unscoped_shared: BTreeSet<String>,
}

impl Findings {
    fn reference(&mut self, row: &'static Instrument, written: &str) {
        self.references
            .entry(row.name)
            .or_default()
            .insert(written.to_owned());
    }

    fn assert_clean(&self, consumer: &str) {
        assert!(
            self.problems.is_empty(),
            "{consumer} queries proxy metrics the contract does not export:\n  {}",
            self.problems.join("\n  ")
        );
        assert!(
            !self.references.is_empty(),
            "no proxy metric was found in {consumer}; the extractor no longer understands it"
        );
    }
}

