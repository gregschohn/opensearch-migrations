fn repository_root() -> PathBuf {
    // crates/capture-observability -> crates -> captureProxy -> TrafficCapture -> repository root
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..");
    assert!(
        root.join("VERSION").is_file() && root.join("deployment/k8s").is_dir(),
        "{} is not the repository root; this test reads the shipped dashboards from the checkout",
        root.display()
    );
    root
}

fn read(relative: &str) -> String {
    let path = repository_root().join(relative);
    fs::read_to_string(&path).unwrap_or_else(|error| panic!("read {}: {error}", path.display()))
}

fn read_json(relative: &str) -> Value {
    serde_json::from_str(&read(relative))
        .unwrap_or_else(|error| panic!("parse {relative}: {error}"))
}

/// The Grafana dashboard JSON out of its Helm template.
///
/// The JSON is the YAML literal block under [`GRAFANA_DASHBOARD_KEY`]. It contains a handful of
/// Helm actions (alert thresholds and a forecast look-back from chart values); each is replaced by
/// `0`, which is valid wherever they appear (a JSON number, or inside a `PromQL` range).
fn grafana_dashboard() -> Value {
    let template = read(GRAFANA_DASHBOARD_TEMPLATE);
    let marker = format!("{GRAFANA_DASHBOARD_KEY}: |");
    let mut lines = template.lines();
    let key_indent = lines
        .by_ref()
        .find_map(|line| (line.trim() == marker).then(|| indentation(line)))
        .unwrap_or_else(|| panic!("{GRAFANA_DASHBOARD_TEMPLATE} has no `{marker}` block"));
    let mut block_indent = None;
    let mut block = String::new();
    for line in lines {
        if line.trim().is_empty() {
            block.push('\n');
            continue;
        }
        let indent = indentation(line);
        if indent <= key_indent {
            break;
        }
        let strip = *block_indent.get_or_insert(indent);
        block.push_str(line.get(strip.min(indent)..).unwrap_or_default());
        block.push('\n');
    }
    serde_json::from_str(&replace_helm_actions(&block))
        .unwrap_or_else(|error| panic!("parse the JSON in {GRAFANA_DASHBOARD_TEMPLATE}: {error}"))
}

fn indentation(line: &str) -> usize {
    line.len() - line.trim_start_matches(' ').len()
}

fn replace_helm_actions(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let end = rest[start..]
            .find("}}")
            .unwrap_or_else(|| panic!("unterminated Helm action in {GRAFANA_DASHBOARD_TEMPLATE}"));
        out.push('0');
        rest = &rest[start + end + 2..];
    }
    out.push_str(rest);
    out
}

/// Every `PromQL` string in a Grafana dashboard: panel target expressions and variable queries.
fn grafana_expressions(dashboard: &Value) -> Vec<String> {
    fn walk(value: &Value, out: &mut Vec<String>) {
        match value {
            Value::Object(map) => {
                for (key, child) in map {
                    match (key.as_str(), child) {
                        ("expr" | "definition" | "query", Value::String(text)) => {
                            out.push(text.clone());
                        }
                        _ => walk(child, out),
                    }
                }
            }
            Value::Array(items) => items.iter().for_each(|item| walk(item, out)),
            _ => {}
        }
    }
    let mut out = Vec::new();
    walk(dashboard, &mut out);
    out
}

