//! The shipped dashboards and operator scripts, tied to the metric contract.
//!
//! [`contract::INSTRUMENTS`] and `metric_contract.rs` pin what the proxy **exports**. Nothing tied
//! that to what the checked-in consumers **query**: a dashboard that names a series the proxy does
//! not export shows an empty panel, never an error. This file reads every shipped consumer from the
//! repository, extracts each proxy metric it queries, and asserts that the metric name, the
//! exported Prometheus series name, and every dimension key and value it uses exist in the
//! contract.
//!
//! | Consumer | Query form | How a proxy metric is recognised |
//! |---|---|---|
//! | [`CLOUDWATCH_DASHBOARD`] and [`CLOUDWATCH_DASHBOARD_CHART_COPY`] | `CloudWatch` metric arrays and `SEARCH` expressions | `OTelLib="captureProxy"` |
//! | [`GRAFANA_DASHBOARD_TEMPLATE`] (JSON embedded in a Helm template) | `PromQL` | the series name, or `otel_scope_name="captureProxy"` |
//! | [`K6_DASHBOARD`] | `PromQL` | the series name, or `exported_job="capture"` |
//! | [`OPERATOR_SCRIPTS`] | free text | the series or instrument name |
//!
//! A metric is treated as the proxy's when it is pinned to the proxy's scope or service, when its
//! name is an exported proxy series, or when it merely **looks** like one: it starts with `capture`
//! and a capital letter, or with a contract instrument name and `_`. The last rule is what catches
//! a unit change: if `fullRequest` lost its `count` unit, the dashboard's `fullRequest_count_total`
//! would no longer resolve, and this test reports it instead of silently classifying it as somebody
//! else's series.
//!
//! The union of everything the consumers read must equal the contract's
//! [`Exposure::ExternallyConsumed`] set, in both directions, so that set stays the verified list of
//! instruments a rename would break.

