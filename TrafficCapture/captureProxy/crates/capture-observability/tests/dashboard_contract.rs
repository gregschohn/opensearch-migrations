/// Proxy names in a script, by token.
///
/// A token counts when it is an exported series name, or an instrument name containing a capital
/// letter (a `{__name__=~"capturePublishingRecordsAwaitingAcknowledgement.*"}` regex names the
/// instrument, not the series). Single-word instrument names (`removed`, `unregistered`) are
/// ordinary English in a script and are not recognised; neither is read by any consumer.
fn check_free_text(text: &str, findings: &mut Findings) {
    let tokens: BTreeSet<&str> = text
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == ':'))
        .filter(|token| !token.is_empty())
        .collect();
    for token in tokens {
        if let Some((row, _)) = resolve_series(token) {
            findings.reference(row, token);
        } else if let Some(row) = contract::instrument(token).filter(|row| distinctive(row)) {
            findings.reference(row, token);
        } else if looks_like_a_proxy_name(token)
            && instrument_prefixing(token).is_none_or(distinctive)
        {
            findings.problems.push(format!(
                "`{token}` looks like a proxy metric but the proxy exports no such instrument or series"
            ));
        }
    }
}

